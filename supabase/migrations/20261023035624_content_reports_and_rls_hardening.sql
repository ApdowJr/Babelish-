-- Learner content reports. Only the signed-in owner can submit/read their own reports.
create table if not exists public.content_reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  language_id text not null,
  kind text not null,
  quote text not null default '',
  reason text not null,
  created_at timestamptz not null default now(),
  status text not null default 'new' check (status in ('new', 'reviewing', 'resolved', 'dismissed'))
);
alter table public.content_reports enable row level security;
drop policy if exists content_reports_insert_own on public.content_reports;
create policy content_reports_insert_own on public.content_reports
  for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists content_reports_read_own on public.content_reports;
create policy content_reports_read_own on public.content_reports
  for select to authenticated using ((select auth.uid()) = user_id);
grant insert, select on public.content_reports to authenticated;
revoke all on public.content_reports from anon;
