/**
 * Starter packs — the free, bundled first words for every language in the
 * atlas. Two curated decks per language:
 *
 *   essentials — greetings + the polite words that unlock a conversation
 *   numbers    — 1–10, the highest-leverage vocabulary after "hello"
 *
 * Pure data (no React/Expo imports) so the curriculum builder, the phrasebook,
 * the Speak tab fallback and the unit tests can all share it.
 */
export type StarterWord = {
  target: string;
  english: string;
  /** Latin transliteration for non-Latin scripts. */
  roman?: string;
};

export type StarterPack = {
  essentials: StarterWord[];
  numbers: StarterWord[];
};

const NUMBERS_EN = [
  'one',
  'two',
  'three',
  'four',
  'five',
  'six',
  'seven',
  'eight',
  'nine',
  'ten',
] as const;

function numbers(
  targets: [string, string, string, string, string, string, string, string, string, string],
  roman?: [string, string, string, string, string, string, string, string, string, string]
): StarterWord[] {
  return targets.map((target, index) => ({
    target,
    english: NUMBERS_EN[index],
    ...(roman ? { roman: roman[index] } : {}),
  }));
}

