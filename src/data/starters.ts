export function starterPack(languageId: string): StarterPack | null {
  return STARTERS[languageId] ?? null;
}

/** Flat list of a language's starter words with a stable category tag. */
export function starterWords(
  languageId: string
): { word: StarterWord; category: 'essentials' | 'numbers' }[] {
  const pack = STARTERS[languageId];
  if (!pack) return [];
  return [
    ...pack.essentials.map((word) => ({ word, category: 'essentials' as const })),
    ...pack.numbers.map((word) => ({ word, category: 'numbers' as const })),
  ];
}
